/**
 * Returns dynamic daily brain teaser puzzle based on today's calendar date
 */
export function getDailyChallengePuzzle(date = new Date()) {
  const dayOfYear = Math.floor(
    (date - new Date(date.getFullYear(), 0, 0)) / 1000 / 60 / 60 / 24
  );
  const index = Math.abs(dayOfYear) % PUZZLE_LEVELS.length;
  const base = PUZZLE_LEVELS[index];

  return {
    ...base,
    isDaily: true,
    coins: base.coins + 30, // Daily bonus coins
    title: {
      en: `Daily Brain Boost: ${base.title.en}`,
      ar: `تحدي اليوم: ${base.title.ar}`,
    },
  };
}

